-- ==============================================================================
-- AI-Based Smart Allocation Engine for PM Internship Scheme
-- PostgreSQL Relational Database Schema (DDL)
-- Compliant with ER Diagram, Tabular ER Diagram, and Class Diagram
-- ==============================================================================

-- Clean up existing tables if rebuilding
DROP TABLE IF EXISTS "Notification" CASCADE;
DROP TABLE IF EXISTS "Allocation" CASCADE;
DROP TABLE IF EXISTS "Requirement" CASCADE;
DROP TABLE IF EXISTS "Internship" CASCADE;
DROP TABLE IF EXISTS "Profile_Analysis" CASCADE;
DROP TABLE IF EXISTS "AI_Matching_Engine" CASCADE;
DROP TABLE IF EXISTS "Student_Profile" CASCADE;
DROP TABLE IF EXISTS "Student" CASCADE;
DROP TABLE IF EXISTS "Organization" CASCADE;
DROP TABLE IF EXISTS "Admin" CASCADE;

-- 1. Student Table
CREATE TABLE "Student" (
    "Student_ID" SERIAL PRIMARY KEY,
    "Name" VARCHAR(100) NOT NULL,
    "Email" VARCHAR(100) UNIQUE NOT NULL,
    "Phone" VARCHAR(15),
    "Password" VARCHAR(255) NOT NULL,
    "DateOfBirth" DATE,
    "IsEmailVerified" BOOLEAN DEFAULT FALSE,
    "CreatedAt" TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt" TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 2. Student Profile Table (1:1 with Student)
CREATE TABLE "Student_Profile" (
    "Profile_ID" SERIAL PRIMARY KEY,
    "Student_ID" INT UNIQUE NOT NULL REFERENCES "Student"("Student_ID") ON DELETE CASCADE,
    "Education" VARCHAR(100) NOT NULL,
    "Degree" VARCHAR(100),
    "Institution" VARCHAR(150),
    "YearOfPassing" INT,
    "Percentage" NUMERIC(5,2),
    "Skills" TEXT NOT NULL, -- Comma-separated or JSON list of skills
    "Experience" TEXT,       -- Summary or JSON list of past experience
    "Interests" TEXT,        -- Domain interests
    "Location_Preference" VARCHAR(100),
    "Resume_Path" VARCHAR(255),
    "ProfileScore" NUMERIC(5,2) DEFAULT 0.00,
    "Status" VARCHAR(30) DEFAULT 'Profile Created', -- Profile Created, Under Review, Verified
    "CreatedAt" TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt" TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 3. AI Matching Engine Metadata Table
CREATE TABLE "AI_Matching_Engine" (
    "Engine_ID" SERIAL PRIMARY KEY,
    "Algorithm" VARCHAR(100) NOT NULL,
    "Model_Version" VARCHAR(50) NOT NULL,
    "Status" VARCHAR(30) DEFAULT 'Active',
    "WeightsConfig" JSONB,
    "Last_Updated" TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 4. Profile Analysis Table (Generated by Engine)
CREATE TABLE "Profile_Analysis" (
    "Analysis_ID" SERIAL PRIMARY KEY,
    "Profile_ID" INT NOT NULL REFERENCES "Student_Profile"("Profile_ID") ON DELETE CASCADE,
    "Engine_ID" INT NOT NULL REFERENCES "AI_Matching_Engine"("Engine_ID") ON DELETE CASCADE,
    "Extracted_Skills" TEXT,
    "Profile_Score" NUMERIC(5,2) NOT NULL DEFAULT 0.00,
    "Analysis_Date" TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    "Feedback" TEXT
);

-- 5. Organization Table
-- NOTE: Corrected from original diagram to include Password, Status, and Verification fields
CREATE TABLE "Organization" (
    "Organization_ID" SERIAL PRIMARY KEY,
    "Organization_Name" VARCHAR(150) NOT NULL,
    "Industry" VARCHAR(100) NOT NULL,
    "Location" VARCHAR(100) NOT NULL,
    "Contact_Person" VARCHAR(100),
    "Contact_Email" VARCHAR(100) UNIQUE NOT NULL,
    "Password" VARCHAR(255) NOT NULL,
    "Status" VARCHAR(30) DEFAULT 'Pending_Approval', -- Pending_Approval, Active, Suspended
    "IsEmailVerified" BOOLEAN DEFAULT FALSE,
    "CreatedAt" TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt" TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 6. Internship Post Table
CREATE TABLE "Internship" (
    "Internship_ID" SERIAL PRIMARY KEY,
    "Organization_ID" INT NOT NULL REFERENCES "Organization"("Organization_ID") ON DELETE CASCADE,
    "Title" VARCHAR(150) NOT NULL,
    "Description" TEXT NOT NULL,
    "Required_Skills" TEXT NOT NULL,
    "Eligibility_Criteria" TEXT,
    "Location" VARCHAR(100) NOT NULL,
    "Duration" VARCHAR(50) NOT NULL,
    "Stipend" NUMERIC(10,2) DEFAULT 0.00,
    "Available_Seats" INT NOT NULL DEFAULT 1,
    "Filled_Seats" INT NOT NULL DEFAULT 0,
    "Status" VARCHAR(30) DEFAULT 'Pending_Approval', -- Draft, Pending_Approval, Active, Closed, Suspended
    "CreatedAt" TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt" TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 7. Requirement Table (Detailed eligibility specs per internship)
CREATE TABLE "Requirement" (
    "Requirement_ID" SERIAL PRIMARY KEY,
    "Internship_ID" INT NOT NULL REFERENCES "Internship"("Internship_ID") ON DELETE CASCADE,
    "Skill" VARCHAR(100) NOT NULL,
    "Qualification" VARCHAR(100),
    "Experience" VARCHAR(100),
    "Location" VARCHAR(100),
    "MinPercentage" NUMERIC(5,2) DEFAULT 60.00
);

-- 8. Allocation Table (Matches Candidates to Posts)
CREATE TABLE "Allocation" (
    "Allocation_ID" SERIAL PRIMARY KEY,
    "Student_ID" INT NOT NULL REFERENCES "Student"("Student_ID") ON DELETE CASCADE,
    "Internship_ID" INT NOT NULL REFERENCES "Internship"("Internship_ID") ON DELETE CASCADE,
    "Engine_ID" INT NOT NULL REFERENCES "AI_Matching_Engine"("Engine_ID") ON DELETE CASCADE,
    "Allocation_Date" DATE DEFAULT CURRENT_DATE,
    "Match_Score" NUMERIC(5,2) NOT NULL,
    "Status" VARCHAR(30) DEFAULT 'Allocation Pending', 
    -- States: Allocation Pending, Under Review, Allocation Finalized, Offer Issued, Offer Accepted, Offer Rejected, In Progress, Completed, Withdrawn
    "Remarks" TEXT,
    "Feedback" TEXT,
    "CreatedAt" TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    "UpdatedAt" TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 9. Notification Table
-- NOTE: Corrected to support recipient role and reference ID
CREATE TABLE "Notification" (
    "Notification_ID" SERIAL PRIMARY KEY,
    "Recipient_Type" VARCHAR(20) DEFAULT 'Student', -- Student, Organization, Admin
    "Student_ID" INT REFERENCES "Student"("Student_ID") ON DELETE CASCADE,
    "Organization_ID" INT REFERENCES "Organization"("Organization_ID") ON DELETE CASCADE,
    "Allocation_ID" INT REFERENCES "Allocation"("Allocation_ID") ON DELETE SET NULL,
    "Message" TEXT NOT NULL,
    "Notification_Date" TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    "Status" VARCHAR(30) DEFAULT 'Unread', -- Unread, Read
    "Type" VARCHAR(50) DEFAULT 'Status_Update' -- Offer, Shortlist, Review, System
);

-- 10. Administrator Table
CREATE TABLE "Admin" (
    "Admin_ID" SERIAL PRIMARY KEY,
    "Name" VARCHAR(100) NOT NULL,
    "Email" VARCHAR(100) UNIQUE NOT NULL,
    "Password" VARCHAR(255) NOT NULL,
    "Role" VARCHAR(50) DEFAULT 'PM Internship Authority',
    "CreatedAt" TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- Indices for high performance queries
CREATE INDEX idx_student_email ON "Student"("Email");
CREATE INDEX idx_org_email ON "Organization"("Contact_Email");
CREATE INDEX idx_internship_status ON "Internship"("Status");
CREATE INDEX idx_allocation_student ON "Allocation"("Student_ID");
CREATE INDEX idx_allocation_internship ON "Allocation"("Internship_ID");
CREATE INDEX idx_allocation_status ON "Allocation"("Status");
